"""Render the catalog as Markdown. No network and no package installs."""

from __future__ import annotations

import re

from t2offsec.catalog import PACKAGE_DISPLAY, PACKAGE_NAME, PACKAGE_VERSION, Catalog, Tool


def _cell(value: str) -> str:
    return value.replace("|", "\\|")


def _fedora(tool: Tool) -> str:
    if tool.fedora == "official":
        text = f"official `{tool.fedora_package}`"
    elif tool.fedora == "copr":
        text = f"COPR `{tool.copr}` package `{tool.fedora_package}`"
    else:
        text = "no Fedora 44 package"
    note = tool.fedora_note
    prefix = "No Fedora 44 package."
    if note.startswith(prefix):
        note = note[len(prefix):].strip()
    if note:
        text = f"{text}. {note}"
    return text


def _license(tool: Tool) -> str:
    if tool.license_note:
        return f"{tool.license}. {tool.license_note}"
    return tool.license


def _table(tools: list[Tool]) -> str:
    lines = [
        "| Tool | Purpose | Upstream | Fedora | License |",
        "| --- | --- | --- | --- | --- |",
    ]
    for tool in tools:
        lines.append(
            "| {name} | {purpose} | {upstream} | {fedora} | {license} |".format(
                name=_cell(tool.name),
                purpose=_cell(tool.purpose),
                upstream=_cell(tool.upstream),
                fedora=_cell(_fedora(tool)),
                license=_cell(_license(tool)),
            )
        )
    return "\n".join(lines)


def render_markdown(catalog: Catalog) -> str:
    lines = [
        "# Offensive tool catalog",
        "",
        "Generated from `catalog/tools.toml`. Regenerate with "
        "`PYTHONPATH=python/src python3 -m t2offsec catalog` and do not edit this file by hand.",
        "",
        f"Fedora availability was read from the Fedora {catalog.fedora_release} mdapi "
        f"on {catalog.checked}. A row marked official is a package name in that compose. "
        "A COPR row is an unofficial build that existed that day. Anything else is an "
        "upstream pointer. This page names tools. It does not describe exploits, payloads, "
        "or attack steps.",
        "",
        "Kali menu coverage:",
        "",
    ]
    for group in catalog.groups:
        if not group.kali_metapackages:
            continue
        packages = ", ".join(f"`{name}`" for name in group.kali_metapackages)
        lines.append(f"- {group.title}: {packages}")
    lines.append("")

    by_id = {tool.id: tool for tool in catalog.tools}
    for group in catalog.groups:
        primary = [tool for tool in catalog.tools if tool.group == group.id]
        extra = [
            by_id[tool.id]
            for tool in catalog.tools
            if group.id in tool.also_in and tool.group != group.id
        ]
        lines.append(f"## {group.title}")
        lines.append("")
        lines.append(group.summary)
        lines.append("")
        if group.kali_metapackages:
            lines.append(
                "Kali metapackage: "
                + ", ".join(f"`{name}`" for name in group.kali_metapackages)
                + "."
            )
            lines.append("")
        if primary:
            lines.append(_table(primary))
            lines.append("")
        elif not extra:
            lines.append("No installable rows. The summary is the whole entry.")
            lines.append("")
        if extra:
            lines.append("Also referenced here:")
            lines.append("")
            lines.append(_table(extra))
            lines.append("")

    gaps = [tool for tool in catalog.tools if tool.fedora != "official"]
    lines.append("## Gaps")
    lines.append("")
    lines.append(
        "These notable tools have no official Fedora "
        f"{catalog.fedora_release} package. COPR is a closest unofficial path, not Fedora itself."
    )
    lines.append("")
    lines.append("| Tool | Group | Closest path | Upstream |")
    lines.append("| --- | --- | --- | --- |")
    for tool in gaps:
        if tool.fedora == "copr":
            path = f"COPR `{tool.copr}` (`{tool.fedora_package}`)"
        else:
            path = "upstream build"
        lines.append(
            f"| {_cell(tool.name)} | {_cell(tool.group)} | {_cell(path)} | {_cell(tool.upstream)} |"
        )
    lines.append("")
    return "\n".join(lines)


def _anchor(title: str) -> str:
    slug = title.lower()
    slug = re.sub(r"[^a-z0-9\s-]", "", slug)
    slug = re.sub(r"\s+", "-", slug.strip())
    return slug


def help_command(tool: Tool) -> str:
    """Command that asks the tool to print its own help. Never a scan or an exploit."""
    if tool.binary:
        return f"{tool.binary} --help"
    if tool.python_distribution:
        return f"pydoc {tool.python_distribution}"
    return ""


def _fedora_package_line(catalog: Catalog, tool: Tool) -> str:
    release = catalog.fedora_release
    if tool.fedora == "official":
        line = f"`{tool.fedora_package}` is the official Fedora {release} package."
    elif tool.fedora == "copr":
        line = (
            f"No official Fedora {release} package. The closest RPM name is "
            f"`{tool.fedora_package}` from COPR `{tool.copr}`."
        )
    else:
        line = f"No Fedora {release} package. Follow the upstream project."
    note = tool.fedora_note
    prefix = f"No Fedora {release} package."
    if note.startswith(prefix):
        note = note[len(prefix) :].strip()
    if note:
        line = f"{line} {note}"
    return line


