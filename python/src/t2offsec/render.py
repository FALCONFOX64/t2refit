def _tool_entry(catalog: Catalog, tool: Tool) -> list[str]:
    help_line = help_command(tool)
    if help_line:
        help_text = f"`{help_line}`"
    else:
        help_text = "No program. Read the upstream page."
    lines = [
        f"#### {tool.name}",
        "",
        tool.purpose,
        "",
        f"- Catalog id: `{tool.id}`",
        f"- Fedora package: {_fedora_package_line(catalog, tool)}",
        f"- Help: {help_text}",
        f"- Upstream: {tool.upstream}",
        f"- License: {_license(tool)}",
    ]
    if tool.also_in:
        names = ", ".join(catalog.group(group_id).title for group_id in tool.also_in)
        lines.append(f"- Also listed under: {names}")
    lines.append("")
    return lines
